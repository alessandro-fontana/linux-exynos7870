#ifndef __MFD_SM5703_H__
#define __MFD_SM5703_H__

#include <linux/bits.h>

/* Interrupt status, cleared on read */
#define SM5703_REG_INT1			0x00
#define SM5703_REG_INT2			0x01
#define SM5703_REG_INT3			0x02
#define SM5703_REG_INT4			0x03

/* Interrupt masks, a set bit masks the interrupt off */
#define SM5703_REG_INTMSK1		0x04
#define SM5703_REG_INTMSK2		0x05
#define SM5703_REG_INTMSK3		0x06
#define SM5703_REG_INTMSK4		0x07

#define SM5703_REG_STATUS1		0x08
#define SM5703_REG_STATUS2		0x09
#define SM5703_REG_STATUS3		0x0a
#define SM5703_REG_STATUS4		0x0b

#define SM5703_REG_CNTL			0x0c
#define SM5703_REG_VBUSCNTL		0x0d
#define SM5703_REG_CHGCNTL1		0x0e
#define SM5703_REG_CHGCNTL2		0x0f
#define SM5703_REG_CHGCNTL3		0x10
#define SM5703_REG_CHGCNTL4		0x11
#define SM5703_REG_CHGCNTL5		0x12
#define SM5703_REG_CHGCNTL6		0x13

#define SM5703_REG_FLEDCNTL1		0x14
#define SM5703_REG_FLEDCNTL6		0x19

#define SM5703_REG_LDO1			0x1a
#define SM5703_REG_LDO2			0x1b
#define SM5703_REG_LDO3			0x1c
#define SM5703_REG_BUCK			0x1d
#define SM5703_REG_DEVICE_ID		0x1e

#define SM5703_REG_OTGCURRENTCNTL	0x60
#define SM5703_REG_Q3LIMITCNTL		0x66
#define SM5703_REG_STATUS5		0x6b

#define SM5703_REG_MAX			0x6b

/* SM5703_REG_CNTL */
#define SM5703_CNTL_OPERATION_MODE_MASK		GENMASK(2, 0)
#define SM5703_CNTL_OPERATION_MODE_SUSPEND	0x0
#define SM5703_CNTL_OPERATION_MODE_CHARGING_OFF	0x4
#define SM5703_CNTL_OPERATION_MODE_CHARGING_ON	0x5
#define SM5703_CNTL_OPERATION_MODE_FLASH_BOOST	0x6
#define SM5703_CNTL_OPERATION_MODE_USB_OTG	0x7
#define SM5703_CNTL_AUTOSET			BIT(4)

/* SM5703_REG_VBUSCNTL */
#define SM5703_VBUSCNTL_VBUSLIMIT		GENMASK(5, 0)

/* SM5703_REG_CHGCNTL2 */
#define SM5703_CHGCNTL2_FASTCHG			GENMASK(5, 0)

/* SM5703_REG_CHGCNTL3 */
#define SM5703_CHGCNTL3_BATREG			GENMASK(4, 0)

/* SM5703_REG_CHGCNTL4 */
#define SM5703_CHGCNTL4_TOPOFF			GENMASK(6, 3)
#define SM5703_CHGCNTL4_AUTOSTOP		BIT(7)

/* SM5703_REG_CHGCNTL5 */
#define SM5703_CHGCNTL5_AICLTH			GENMASK(2, 0)
#define SM5703_CHGCNTL5_TOPOFF_TIMER		GENMASK(6, 5)
#define SM5703_CHGCNTL5_AICLEN			BIT(7)

/* SM5703_REG_CHGCNTL6 */
#define SM5703_CHGCNTL6_FREQSEL			GENMASK(3, 2)
#define SM5703_CHGCNTL6_FREQSEL_1P5MHZ		0x2

/* SM5703_REG_STATUS1 */
#define SM5703_STATUS1_AICL			BIT(0)
#define SM5703_STATUS1_BATOVP			BIT(1)
#define SM5703_STATUS1_OTGFAIL			BIT(6)

/* SM5703_REG_STATUS2 */
#define SM5703_STATUS2_THEMREG			BIT(0)
#define SM5703_STATUS2_THEMSHDN			BIT(1)
#define SM5703_STATUS2_NOBAT			BIT(4)

/* SM5703_REG_STATUS3 */
#define SM5703_STATUS3_CHGON			BIT(0)
#define SM5703_STATUS3_Q4FULLON			BIT(1)
#define SM5703_STATUS3_TOPOFF			BIT(2)
#define SM5703_STATUS3_DONE			BIT(3)

/* SM5703_REG_STATUS5 */
#define SM5703_STATUS5_VBUSOK			BIT(5)
#define SM5703_STATUS5_VBUSUVLO			BIT(6)
#define SM5703_STATUS5_VBUSOVP			BIT(7)

enum sm5703_irq {
	SM5703_IRQ_AICL = 0,
	SM5703_IRQ_BATOVP,
	SM5703_IRQ_LOWBATT,
	SM5703_IRQ_VBUSLIMIT,
	SM5703_IRQ_DISLIMIT,
	SM5703_IRQ_VSYSOLP,
	SM5703_IRQ_OTGFAIL,

	SM5703_IRQ_THEMREG,
	SM5703_IRQ_THEMSHDN,
	SM5703_IRQ_VSYSNG,
	SM5703_IRQ_VSYSOK,
	SM5703_IRQ_NOBAT,
	SM5703_IRQ_PRETMROFF,
	SM5703_IRQ_FASTTMROFF,

	SM5703_IRQ_CHGON,
	SM5703_IRQ_Q4FULLON,
	SM5703_IRQ_TOPOFF,
	SM5703_IRQ_DONE,
	SM5703_IRQ_CHGRSTF,

	SM5703_IRQ_FLEDSHORT,
	SM5703_IRQ_FLEDOPEN,
	SM5703_IRQ_BOOSTPOK_NG,
	SM5703_IRQ_BOOSTPOK,
	SM5703_IRQ_ABSTMRON,
};

#endif /* __MFD_SM5703_H__ */
